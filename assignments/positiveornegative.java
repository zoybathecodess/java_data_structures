import java.util.*;
public class positiveornegative {
    public static void main(String[] args) {
        try(Scanner scn=new Scanner(System.in)){
            int n1=scn.nextInt();
            if(n1>=0){
                System.out.println("positive");
            }
            else{
                System.out.println("negative");
            }
        }
    }
}

    

